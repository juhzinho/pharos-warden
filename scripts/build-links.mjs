// Copies ProsPilot's curated link-scanner lists (../pharos-agent/lib/link-scanner/domains.ts, and the TLD and
// shortener lists of link-scanner.ts) into lib/link-domains.js, as plain JavaScript.  node scripts/build-links.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../../pharos-agent/lib/link-scanner/", import.meta.url);
const domains = readFileSync(new URL("domains.ts", dir), "utf8").replace(/: string\[\]/g, "").replace(/: Record<string, string>/g, "");
const scanner = readFileSync(new URL("../link-scanner.ts", dir), "utf8");
const set = (name) => scanner.match(new RegExp(`const ${name} = new Set\\(\\[([\\s\\S]*?)\\]\\)`))[1];
const out = `// Generated by scripts/build-links.mjs from ProsPilot's link scanner (github.com/juhzinho/pharos-agent) — do not edit.
${domains.trim()}

export const SUSPICIOUS_TLDS = new Set([${set("SUSPICIOUS_TLDS").trim()}]);
export const SHORTENERS = new Set([${set("SHORTENERS").trim()}]);
`;
writeFileSync(new URL("../lib/link-domains.js", import.meta.url), out);
console.log("lib/link-domains.js written");
