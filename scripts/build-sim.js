// Copies the runtime bytecode of the simulation doubles (never deployed; used only in eth_call state
// overrides) from the Foundry build into lib/sim-bytecode.js, so the server needs no compiler.
//   node scripts/build-sim.js        (after: cd contracts && forge build)
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => JSON.parse(readFileSync(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url), "utf8")).deployedBytecode.object;
const out = `// Generated by scripts/build-sim.js from contracts/src/test-doubles — do not edit.
// Runtime code used ONLY inside eth_call state overrides for dry runs. Never deployed.
export const SIM_PERMIT2_CODE = "${read("SimPermit2")}";
export const SIM_RUNNER_CODE = "${read("SimRunner")}";
export const SIM_PROBE_CODE = "${read("SimProbe")}";
`;
writeFileSync(new URL("../lib/sim-bytecode.js", import.meta.url), out);
console.log("lib/sim-bytecode.js written");
